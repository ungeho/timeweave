/**
 * Generate a random UUID (RFC 4122 version 4).
 *
 * `crypto.randomUUID` exists only in a SECURE CONTEXT (https, or localhost).
 * Opened over plain http on another host -- a phone on the home LAN reaching
 * the dev server, measured in P8-mobile-1 -- it is undefined, and saving an
 * event in local mode failed with "crypto.randomUUID is not a function".
 * `crypto.getRandomValues` is the same CSPRNG and is available in every
 * context, so the fallback builds the UUID from it. There is deliberately no
 * Math.random path: with no CSPRNG this throws rather than invent an id.
 *
 * Only the local-mode event repository calls this; in Supabase mode the
 * database assigns ids. Share-link tokens are generated by the server and do
 * not pass through here.
 */
export function newId(): string {
  const c = globalThis.crypto;
  if (typeof c?.randomUUID === 'function') return c.randomUUID();
  if (typeof c?.getRandomValues !== 'function') {
    throw new Error('No cryptographic random source is available to generate an id.');
  }
  const b = c.getRandomValues(new Uint8Array(16));
  b[6] = (b[6]! & 0x0f) | 0x40; // version 4
  b[8] = (b[8]! & 0x3f) | 0x80; // variant 10xx
  const h = Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
